# 4. Python Boolean Data Type
'''Boolean data type is a built-in data type in Python. It can have one of the two values: True or False.'''
a = True
b = False
print(a, b)
print(type(a), type(b)) 

# 5. Python None Data Type
'''None is a special constant in Python that represents the absence of a value or a null value  '''
var = None
